// ---- Core i18n engine ----
function t(key) {
  const lang = getLang();
  return (translations[lang] && translations[lang][key]) || translations['fr'][key] || key;
}

function getLang() {
  return localStorage.getItem('y8x_lang') || 'fr';
}

function setLang(lang) {
  localStorage.setItem('y8x_lang', lang);
  applyTranslations();
  updateLangSwitcher();
  document.documentElement.lang = lang;
  // Notify other scripts that language changed
  document.dispatchEvent(new CustomEvent('y8x-lang-changed', { detail: { lang } }));
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = t(key);
    } else {
      el.textContent = t(key);
    }
  });
  // data-i18n-html for elements with inner HTML (icons etc)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    const val = t(key);
    if (val) el.innerHTML = val;
  });
}

function updateLangSwitcher() {
  const lang = getLang();
  const flags = { fr: '🇫🇷', en: '🇬🇧', es: '🇪🇸' };
  const names = { fr: 'FR', en: 'EN', es: 'ES' };
  const btn = document.getElementById('langBtn');
  if (btn) btn.innerHTML = `${flags[lang]} ${names[lang]} <svg width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5"><polyline points="6 9 12 15 18 9"/></svg>`;

  document.querySelectorAll('.lang-option').forEach(opt => {
    opt.classList.toggle('active', opt.dataset.lang === lang);
  });
}

// ---- Language modal (first visit) ----
function showLangModal() {
  const modal = document.getElementById('langModal');
  if (modal) {
    modal.classList.add('visible');
    document.body.style.overflow = 'hidden';
  }
}

function hideLangModal() {
  const modal = document.getElementById('langModal');
  if (modal) {
    modal.classList.remove('visible');
    document.body.style.overflow = '';
  }
}

// ---- Init ----
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('y8x_lang');

  // Show modal only on first visit
  if (!savedLang) {
    showLangModal();
  } else {
    applyTranslations();
    updateLangSwitcher();
  }

  // Modal lang selection
  document.querySelectorAll('.lang-modal-option').forEach(btn => {
    btn.addEventListener('click', () => {
      const lang = btn.dataset.lang;
      setLang(lang);
      hideLangModal();
    });
  });

  // Dropdown switcher
  const langBtn = document.getElementById('langBtn');
  const langDropdown = document.getElementById('langDropdown');

  if (langBtn && langDropdown) {
    langBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      langDropdown.classList.toggle('open');
    });

    document.addEventListener('click', () => {
      langDropdown.classList.remove('open');
    });

    document.querySelectorAll('.lang-option').forEach(opt => {
      opt.addEventListener('click', () => {
        setLang(opt.dataset.lang);
        langDropdown.classList.remove('open');
      });
    });
  }
});
